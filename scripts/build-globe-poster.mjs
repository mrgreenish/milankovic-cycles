// Renders the title globe once and saves it as the loading placeholder.
// Run against a running production server:
//   npm run build && npm run start   (in one terminal)
//   npm run poster:build             (in another; pass a URL to use a different server)
//
// The sprite is the real scene's first frame (Earth, clouds, atmosphere), cropped
// to a circle, so the placeholder and the live scene line up pixel for pixel.
import { chromium } from "@playwright/test";
import sharp from "sharp";
import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const base = process.argv[2] ?? process.env.POSTER_BASE_URL ?? "http://127.0.0.1:3000";
// The Earth's size scales with the page height, so a tall viewport gives a
// sharp sprite. Its share of the height is what the page uses to size it.
const VIEW = { width: 2880, height: 1800 };
const WIDTHS = [1000, 1600];
const out = resolve("public/images");
await mkdir(out, { recursive: true });

const browser = await chromium.launch({
  channel: process.platform === "darwin" ? "chrome" : undefined,
  args:
    process.platform === "darwin"
      ? ["--use-angle=metal", "--enable-webgl", "--ignore-gpu-blocklist"]
      : ["--enable-unsafe-swiftshader"],
});
const context = await browser.newContext({ viewport: VIEW, deviceScaleFactor: 1 });
await context.route("**/_vercel/**", (route) => route.fulfill({ status: 200, body: "" }));
const page = await context.newPage();
await page.addInitScript(() => {
  // Time zero and the top tier: the same state the scene starts in.
  window.__ORBITAL_SCENE_TEST__ = { time: 0, quality: "high" };
  // Keep the drawing buffer so the canvas can be read back after it is shown.
  const getContext = HTMLCanvasElement.prototype.getContext;
  HTMLCanvasElement.prototype.getContext = function (type, attributes) {
    if (typeof type === "string" && type.startsWith("webgl"))
      attributes = { ...attributes, preserveDrawingBuffer: true };
    return getContext.call(this, type, attributes);
  };
});
await page.goto(base + "/", { waitUntil: "networkidle" });
await page.locator('.scene-viewport[data-ready="true"]').waitFor({ timeout: 60000 });
await page.locator('canvas[data-texture-tier="day-4096"]').waitFor({ timeout: 30000 });
await page.waitForTimeout(1500);
const dataUrl = await page.evaluate(() =>
  document.querySelector(".scene-viewport canvas").toDataURL("image/png"),
);
await browser.close();

const frame = Buffer.from(dataUrl.split(",")[1], "base64");
const { data, info } = await sharp(frame)
  .ensureAlpha()
  .raw()
  .toBuffer({ resolveWithObject: true });

// The solid disc is the Earth; clouds and atmosphere fade out beyond it.
let minX = info.width, maxX = 0, minY = info.height, maxY = 0;
for (let y = 0; y < info.height; y += 1) {
  for (let x = 0; x < info.width; x += 1) {
    if (data[(y * info.width + x) * 4 + 3] < 250) continue;
    if (x < minX) minX = x;
    if (x > maxX) maxX = x;
    if (y < minY) minY = y;
    if (y > maxY) maxY = y;
  }
}
const cx = (minX + maxX) / 2;
const cy = (minY + maxY) / 2;
const radius = (maxX - minX + (maxY - minY)) / 4;
// Keep the atmosphere glow (it ends near 1.04 R) and drop everything past it,
// including stars, which the live scene draws on its own.
const keep = radius * 1.07;
const side = Math.round(keep * 2);
const left = Math.round(cx - keep);
const top = Math.round(cy - keep);
const mask = Buffer.from(
  `<svg xmlns="http://www.w3.org/2000/svg" width="${side}" height="${side}"><defs><radialGradient id="g" cx="50%" cy="50%" r="50%"><stop offset="0.93" stop-color="#fff"/><stop offset="1" stop-color="#000"/></radialGradient></defs><rect width="${side}" height="${side}" fill="url(#g)"/></svg>`,
);
const square = await sharp(frame)
  .extract({ left, top, width: side, height: side })
  .composite([{ input: await sharp(mask).png().toBuffer(), blend: "dest-in" }])
  .png()
  .toBuffer();

const files = [];
for (const width of WIDTHS) {
  const name = `globe-poster-${width}.webp`;
  const buffer = await sharp(square)
    .resize(width, width)
    .webp({ quality: 80, alphaQuality: 90, effort: 6, smartSubsample: true })
    .toBuffer();
  await writeFile(resolve(out, name), buffer);
  files.push({ name, width, bytes: buffer.length });
}

const ratio = side / VIEW.height;
await writeFile(
  resolve("src/components/experience/globePoster.generated.ts"),
  `// Generated by scripts/build-globe-poster.mjs. Do not edit by hand.
// \`ratio\` is the sprite's width as a share of the page height at the title view.
export const GLOBE_POSTER = {
  ratio: ${ratio.toFixed(5)},
  src: "/images/${files[0].name}",
  srcSet: "${files.map((f) => `/images/${f.name} ${f.width}w`).join(", ")}",
} as const;
`,
);
console.log(
  `Earth centre ${cx.toFixed(1)}, ${cy.toFixed(1)}  radius ${radius.toFixed(1)}px  (${((radius * 2) / VIEW.height).toFixed(4)} of the height)`,
);
for (const file of files) console.log(`${file.name}  ${(file.bytes / 1024).toFixed(0)} KB`);
console.log(`sprite ratio ${ratio.toFixed(5)}`);
