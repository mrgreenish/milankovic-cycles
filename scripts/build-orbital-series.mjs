// Reproducible offline data build. See src/lib/orbital/README.md for sources.
// Run: npm run series:build -- INSOLN.LA2004.BTL.ASC INSOLP.LA2004.BTL.ASC LR04stack.txt
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const [pastPath, futurePath, icePath] = process.argv.slice(2);
if (!pastPath || !futurePath || !icePath)
  throw new Error(
    "Supply the La2004 past file, the La2004 future file and the LR04 stack, in that order.",
  );

const START_KYR = -800;
const END_KYR = 100;
const ICE_END_KA = 800;
const degrees = (radians) => (radians * 180) / Math.PI;

// La2004 rows: time (kyr), eccentricity, obliquity (rad), perihelion longitude
// from the moving equinox (rad). Fortran writes exponents with a D.
async function la2004(path) {
  const rows = new Map();
  for (const line of (await readFile(path, "utf8")).split(/\r?\n/)) {
    const fields = line.trim().split(/\s+/);
    if (fields.length !== 4) continue;
    const [kyr, eccentricity, obliquity, perihelion] = fields.map((field) =>
      Number(field.replace("D", "E")),
    );
    if (![kyr, eccentricity, obliquity, perihelion].every(Number.isFinite))
      throw new Error(`Unreadable La2004 row in ${path}: ${line}`);
    rows.set(kyr, {
      eccentricity,
      obliquityDeg: degrees(obliquity),
      perihelionDeg: ((degrees(perihelion) % 360) + 360) % 360,
    });
  }
  return rows;
}

const past = await la2004(pastPath);
const future = await la2004(futurePath);
const eccentricity = [];
const obliquityDeg = [];
const perihelionDeg = [];
for (let kyr = START_KYR; kyr <= END_KYR; kyr++) {
  const row = (kyr <= 0 ? past : future).get(kyr);
  if (!row) throw new Error(`La2004 has no row for ${kyr} kyr.`);
  eccentricity.push(Number(row.eccentricity.toFixed(9)));
  obliquityDeg.push(Number(row.obliquityDeg.toFixed(6)));
  perihelionDeg.push(Number(row.perihelionDeg.toFixed(6)));
}

// LR04 rows: age (ka), benthic d18O (per mil), standard error. The stack is
// sampled every 1 kyr to 600 ka and every 2 kyr beyond, so fill the gaps.
const measured = [];
for (const line of (await readFile(icePath, "utf8")).split(/\r?\n/)) {
  const fields = line.trim().split(/\s+/);
  if (fields.length !== 3) continue;
  const [age, value] = fields.map(Number);
  if (Number.isFinite(age) && Number.isFinite(value))
    measured.push({ age, value });
}
measured.sort((a, b) => a.age - b.age);
const d18O = [];
for (let age = 0, cursor = 0; age <= ICE_END_KA; age++) {
  while (cursor < measured.length - 2 && measured[cursor + 1].age < age)
    cursor++;
  const before = measured[cursor];
  const after = measured[cursor + 1];
  if (before.age > age || after.age < age)
    throw new Error(`LR04 does not cover ${age} ka.`);
  const mix = (age - before.age) / (after.age - before.age);
  d18O.push(Number((before.value + (after.value - before.value) * mix).toFixed(3)));
}

const list = (values) => `[\n  ${values.join(",\n  ")},\n]`;
const header =
  "// Generated by scripts/build-orbital-series.mjs. Do not edit by hand.\n";

await writeFile(
  resolve("src/lib/orbital/series.generated.ts"),
  `${header}// La2004 nominal solution (Laskar et al. 2004), one row per 1,000 years.
// Index 0 is ${START_KYR} kyr; the last index is +${END_KYR} kyr; J2000 is index ${-START_KYR}.
export const SERIES_START_KYR = ${START_KYR};
export const SERIES_END_KYR = ${END_KYR};
export const SERIES_ECCENTRICITY: readonly number[] = ${list(eccentricity)};
export const SERIES_OBLIQUITY_DEG: readonly number[] = ${list(obliquityDeg)};
export const SERIES_PERIHELION_DEG: readonly number[] = ${list(perihelionDeg)};
`,
);
await writeFile(
  resolve("src/lib/orbital/iceRecord.generated.ts"),
  `${header}// LR04 benthic d18O stack (Lisiecki & Raymo 2005), per mil, one value per
// 1,000 years. Index 0 is today; the last index is ${ICE_END_KA},000 years ago.
// Values beyond 600 ka are linear fills of the 2-kyr source spacing.
export const ICE_RECORD_END_KA = ${ICE_END_KA};
export const ICE_RECORD_D18O: readonly number[] = ${list(d18O)};
`,
);

const range = (values) =>
  `${Math.min(...values)} to ${Math.max(...values)}`;
console.log(`Orbit rows: ${eccentricity.length} (${START_KYR} to +${END_KYR} kyr)`);
console.log(`  eccentricity ${range(eccentricity)}`);
console.log(`  obliquity    ${range(obliquityDeg)} degrees`);
console.log(`Ice rows: ${d18O.length} (0 to ${ICE_END_KA} ka), d18O ${range(d18O)}`);
